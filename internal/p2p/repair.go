// REPAIR
// ======
// "When a node drops out the missing pieces are reconstructed."
//
// A holder disappearing is not detectable from a manifest, because a manifest
// says which shards exist, never where they are. With the placement ledger it
// becomes a plain question: for each chunk, ask every recorded holder whether it
// still has the shard, drop the ones that say no or cannot be reached at all,
// and if that leaves fewer distinct remote shard indexes than dataShards,
// rebuild the missing shards from any dataShards survivors and place the
// regenerated bytes on peers that hold NO shard of that chunk.
//
// The last clause is the part that is easy to get wrong. Re-placing a
// regenerated shard on a node that already holds a sibling restores the shard
// count while leaving the object no more survivable than before -- exactly the
// failure the round-robin distributor had. Repair reuses the same planner as
// dispersal so it cannot reintroduce it.

const (
	// repairInterval is the audit cadence. Slower than dispersal: dispersal is
	// racing to make a new object durable, repair is maintaining objects that
	// are already somewhere.
	repairInterval = 30 * time.Minute
	// repairObjectsPerPass bounds how many objects one pass will touch.
	repairObjectsPerPass = 8
	// repairShardsPerPass is the hard ceiling on regenerated shards per pass.
	//
	// THIS IS THE STORM BRAKE. A netsplit makes EVERY holder unreachable at
	// once, so an unthrottled repair would conclude that every object on the
	// node had lost every remote copy and would try to rebuild and re-push the
	// entire catalogue -- tens of thousands of shards, each with a coordinator
	// lease, at the exact moment the network is least able to carry it, and all
	// of it wasted because the holders come back. The budget means the worst a
	// total netsplit costs is this many shards per half hour until the peers
	// return and the audit finds them healthy again.
	repairShardsPerPass = 48
	// repairCooldown is the minimum time before the same object is audited
	// again. Persisted in the ledger (ObjectPlacement.LastAttempt) rather than
	// held in memory, because a crash loop is precisely when an in-memory
	// cooldown stops working and a repair storm is least affordable.
	repairCooldown = 6 * time.Hour
	// repairMinHolderChecks is how many recorded holders must answer before a
	// silent holder is treated as gone. If NOBODY answers, this node is the one
	// that is netsplit, not the holders, and forgetting them all would destroy
	// the ledger's knowledge of where the object lives.
	repairMinHolderChecks = 1
)

// ErrRepairInFlight means another goroutine already holds the repair slot for
// this shard.
var ErrRepairInFlight = errors.New("shard is already being repaired")

// beginRepair claims the single-flight slot for a shard.
//
// Repair is triggered from two places (the periodic pass and a dispersal that
// finds a chunk short), passes can overlap when one runs long, and the same
// shard id can appear under more than one object because shards are
// content-addressed. Two concurrent repairs of one shard would regenerate the
// same bytes twice, take two leases, and race each other into the ledger.
func (n *Node) beginRepair(shardID string) bool {
	n.repairMu.Lock()
	defer n.repairMu.Unlock()
	if n.repairing == nil {
		n.repairing = make(map[string]struct{})
	}
	if _, busy := n.repairing[shardID]; busy {
		return false
	}
	n.repairing[shardID] = struct{}{}
	return true
}

func (n *Node) endRepair(shardID string) {
	n.repairMu.Lock()
	defer n.repairMu.Unlock()
	delete(n.repairing, shardID)
}

// RepairStored audits placement and rebuilds what node losses took away.
func (n *Node) RepairStored(ctx context.Context) {
	for {
		timer := time.NewTimer(repairInterval)
		select {
		case <-ctx.Done():
			timer.Stop()
			return
		case <-timer.C:
		}
		n.repairOnce(ctx)
	}
}

func (n *Node) repairOnce(ctx context.Context) {
	if len(n.host.Network().Peers()) == 0 {
		// Distinguishable from healthy. A node with no peers cannot tell a dead
		// holder from its own isolation, and must not act as though it could.
		n.logger.Printf("repair: no peers connected; audit skipped")
		return
	}
	// AuditCandidates, not DispersalCandidates: a fully dispersed object has
	// nothing left to place but is exactly the object whose holder might have
	// gone away, and auditing only the ones that already look broken means a
	// healthy object decays to nothing with nobody asking.
	candidates, err := n.store.AuditCandidates(repairObjectsPerPass, repairCooldown)
	if err != nil {
		n.logger.Printf("repair: cannot read the placement ledger: %v", err)
		return
	}
	if len(candidates) == 0 {
		return
	}
	budget := repairShardsPerPass
	audited, regenerated, replaced := 0, 0, 0
	for _, row := range candidates {
		if ctx.Err() != nil || budget <= 0 {
			break
		}
		result := n.repairObject(ctx, row, &budget)
		audited++
		regenerated += result.regenerated
		replaced += result.replaced
	}
	n.logger.Printf("repair: audited %d object(s), regenerated %d shard(s), re-placed %d",
		audited, regenerated, replaced)
}

type repairOutcome struct {
	regenerated int
	replaced    int
}

// repairObject audits and repairs one object's chunks.
func (n *Node) repairObject(ctx context.Context, row store.ObjectPlacement, budget *int) repairOutcome {
	var outcome repairOutcome
	_ = n.store.MarkPlacementAttempt(row.ObjectID)

	manifest, err := n.store.HeadObject(row.Bucket, row.Key)
	if err != nil {
		// The object is gone but the ledger row survived (a delete path that
		// predates the ledger). Drop it rather than repairing a ghost forever.
		n.logger.Printf("repair: %s/%s no longer exists; dropping its placement row",
			row.Bucket, row.Key)
		_ = n.store.ForgetPlacement(row.ObjectID)
		return outcome
	}
	n.auditHolders(ctx, row)

	fresh, err := n.store.LoadObjectPlacement(row.ObjectID)
	if err != nil {
		return outcome
	}
	candidates := n.storageCandidates(ctx)
	if len(candidates) == 0 {
		return outcome
	}

	for _, chunkIndex := range fresh.ChunkIndexes() {
		if ctx.Err() != nil || *budget <= 0 {
			break
		}
		shards := fresh.PlacementSnapshot(chunkIndex)
		remote := placement.RemoteIndexCount(shards)
		if remote >= len(shards) {
			continue
		}
		// Regenerate only what is genuinely absent: a shard whose bytes are
		// still on local disk needs placing, not rebuilding.
		regenerated, err := n.restoreChunkBytes(ctx, *manifest, chunkIndex, shards, budget)
		if err != nil {
			n.logger.Printf("repair: chunk %d of %s is not rebuildable: %v",
				chunkIndex, shortID(row.ObjectID), err)
			continue
		}
		outcome.regenerated += regenerated
	}

	// One placement round over the whole object, reading regenerated bytes back
	// from local disk. The planner sees the audited holder lists, so a
	// regenerated shard can only land on a peer holding no sibling.
	result := n.placeShards(ctx, row.ObjectID, candidates,
		func(shardID string) ([]byte, error) { return n.store.ReadShard(shardID) })
	outcome.replaced += result.Placed
	return outcome
}

// auditHolders asks every recorded holder whether it still has the shard and
// forgets the ones that do not.
func (n *Node) auditHolders(ctx context.Context, row store.ObjectPlacement) {
	answered, silent := 0, 0
	type verdict struct {
		shardID string
		holder  string
	}
	var gone []verdict
	for _, shard := range row.Shards {
		for _, holder := range shard.Holders {
			if ctx.Err() != nil {
				return
			}
			target, err := peer.Decode(holder)
			if err != nil {
				gone = append(gone, verdict{shard.ShardID, holder})
				continue
			}
			has, err := n.PeerHasShard(ctx, target, shard.ShardID)
			if err != nil {
				// Unreachable is not the same as "does not have it". Counted
				// separately so a local netsplit cannot wipe the ledger.
				silent++
				continue
			}
			answered++
			if !has {
				gone = append(gone, verdict{shard.ShardID, holder})
			}
		}
	}
	if answered < repairMinHolderChecks && silent > 0 {
		n.logger.Printf(
			"repair: %d holder(s) of %s unreachable and none answered; treating this node as isolated rather than the holders as lost",
			silent, shortID(row.ObjectID))
		return
	}
	for _, item := range gone {
		if err := n.store.DropShardHolder(row.ObjectID, item.shardID, item.holder); err != nil {
			continue
		}
		n.logger.Printf("repair: %s no longer holds shard %s", item.holder, shortID(item.shardID))
	}
}

// restoreChunkBytes rebuilds the shards of one chunk that neither this node nor
// any recorded holder still has, from any dataShards survivors.
//
// It returns the number of shards regenerated. Reconstruction is the same
// Reed-Solomon operation a read performs; the difference is that the rebuilt
// bytes are written back to local disk so the placement round that follows has
// something to send.
func (n *Node) restoreChunkBytes(
	ctx context.Context, manifest store.Manifest, chunkIndex int,
	shards []placement.Shard, budget *int,
) (int, error) {
	var chunk store.ChunkManifest
	found := false
	for _, candidate := range manifest.Chunks {
		if candidate.Index == chunkIndex {
			chunk, found = candidate, true
			break
		}
	}
	if !found {
		return 0, errors.New("chunk is not in the manifest")
	}
	total := manifest.DataShards + manifest.ParityShards

	// Claim the single-flight slot for every shard of the chunk BEFORE any
	// network work: reconstruction produces all of them at once, so the unit of
	// exclusion is the chunk's shard set, not one shard.
	var claimed []string
	defer func() {
		for _, id := range claimed {
			n.endRepair(id)
		}
	}()
	for _, ref := range chunk.Shards {
		if !n.beginRepair(ref.ID) {
			return 0, ErrRepairInFlight
		}
		claimed = append(claimed, ref.ID)
	}

	holders := make(map[string][]string, len(shards))
	for _, shard := range shards {
		holders[shard.ID] = shard.Holders
	}

	values := make([][]byte, total)
	missing := 0
	have := 0
	for _, ref := range chunk.Shards {
		if ref.Index < 0 || ref.Index >= total {
			return 0, errors.New("shard index outside the erasure layout")
		}
		if value, err := n.store.ReadShard(ref.ID); err == nil {
			values[ref.Index] = value
			have++
			continue
		}
		fetchCtx, cancel := context.WithTimeout(ctx, 3*time.Minute)
		value, err := n.FetchShard(fetchCtx, ref.ID, holders[ref.ID])
		cancel()
		if err == nil {
			values[ref.Index] = value
			have++
			continue
		}
		missing++
	}
	if missing == 0 {
		return 0, nil
	}
	if have < manifest.DataShards {
		return 0, errors.New("fewer than dataShards survivors; this chunk is lost")
	}
	if missing > *budget {
		missing = *budget
	}
	if missing == 0 {
		return 0, nil
	}

	encoder, err := reedsolomon.New(manifest.DataShards, manifest.ParityShards)
	if err != nil {
		return 0, err
	}
	if err := encoder.Reconstruct(values); err != nil {
		return 0, err
	}
	restored := 0
	for _, ref := range chunk.Shards {
		if *budget <= 0 {
			break
		}
		if _, err := n.store.ReadShard(ref.ID); err == nil {
			continue
		}
		value := values[ref.Index]
		if value == nil {
			continue
		}
		// PutRegeneratedShard verifies the content address, so a reconstruction
		// that produced the wrong bytes is refused rather than stored.
		if err := n.store.PutRegeneratedShard(ref.ID, value); err != nil {
			n.logger.Printf("repair: could not store regenerated shard %s: %v", shortID(ref.ID), err)
			continue
		}
		_ = n.store.SetShardLocal(manifest.ObjectID, ref.ID, true)
		restored++
		*budget--
	}
	if restored > 0 {
		n.logger.Printf("repair: rebuilt %d shard(s) of chunk %d of %s from %d survivors",
			restored, chunkIndex, shortID(manifest.ObjectID), have)
	}
	return restored, nil
}
